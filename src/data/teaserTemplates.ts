export function getTeaserInsight(category: string, lang: Language): TeaserInsight {
  const norm = category.toLowerCase();
  let key = 'generic';

  if (norm.includes('dairy') || norm.includes('दुग्ध') || norm.includes('डेअरी') || norm.includes('दूध')) {
    key = 'dairy';
  } else if (norm.includes('flower') || norm.includes('फुल') || norm.includes('पुष्प') || norm.includes('हार')) {
    key = 'flower';
  } else if (norm.includes('food') || norm.includes('खाद्य') || norm.includes('नाश्ता') || norm.includes('मेस') || norm.includes('टिफिन')) {
    key = 'food';
  } else if (norm.includes('retail') || norm.includes('किराणा') || norm.includes('दुकान') || norm.includes('store')) {
    key = 'retail';
  } else if (norm.includes('farm') || norm.includes('शेती') || norm.includes('कृषी') || norm.includes('agri')) {
    key = 'farming';
  }

  const categoryTemplates = TEASER_TEMPLATES[key] || TEASER_TEMPLATES.generic;
  return categoryTemplates[lang] || categoryTemplates.en || TEASER_TEMPLATES.generic.en;
}
